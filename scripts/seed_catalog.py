async def _ensure_one(session, model, *, check_field: str, check_value, **fields):
    """Создаёт объект, если его ещё нет (идемпотентно по полю ``check_field``)."""
    existing = await catalog_service.list_all(session, model)
    for obj in existing:
        if getattr(obj, check_field) == check_value:
            return obj
    return await catalog_service.create_one(session, model, **fields)


async def main() -> None:
    random.seed(7)
    async with async_session_factory() as session:
        # --- Инфраструктура: склад, фирма, касса, контрагент, тип цен ---
        sklad = await _ensure_one(
            session, cat.Sklad, check_field="code", check_value="01",
            code="01", name="Основной склад", tip="optovy",
        )
        await _ensure_one(
            session, cat.Firma, check_field="inn", check_value="7712345678",
            name="ООО Универсал Трейд", inn="7712345678",
        )
        await _ensure_one(
            session, cat.Kassa, check_field="name", check_value="Касса №1",
            name="Касса №1",
        )
        supplier = await _ensure_one(
            session, cat.Kontragent, check_field="name", check_value="ООО Продснаб",
            code="900", name="ООО Продснаб", inn="7711112222",
        )
        if not await catalog_service.list_all(session, cat.TipTsen):
            await catalog_service.create_one(
                session, cat.TipTsen, name="Розничная", markup_percent=Decimal("35")
            )

        # --- Категории (иерархия: родитель «Продукты» + плоские категории) ---
        categories: dict[str, cat.Category] = {}
        for cat_name in CATALOG:
            categories[cat_name] = await _ensure_one(
                session, cat.Category, check_field="name", check_value=cat_name,
                name=cat_name, sort=len(categories),
            )

        # --- Номенклатура по категориям ---
        created: list[cat.Nomenklatura] = []
        existing_names = {n.name for n in await catalog_service.list_all(session, cat.Nomenklatura)}
        for cat_name, items in CATALOG.items():
            category_id = categories[cat_name].id
            for name, pur, ret in items:
                if name in existing_names:
                    continue
                code = await catalog_service.next_nomenklatura_code(session)
                created.append(
                    await catalog_service.create_one(
                        session, cat.Nomenklatura, code=code, name=name, vid="tovar",
                        purchase_price=Decimal(pur), retail_price=Decimal(ret),
                        category_id=category_id,
                    )
                )

        # --- Приход: оприходуем только что созданные товары (если есть) ---
        if created:
            await catalog_service.set_constant(session, "restock_control", "none")
            today = date.today()
            for i in range(0, len(created), 10):
                chunk = created[i : i + 10]
                items = [
                    {
                        "nomenklatura_id": n.id,
                        "quantity": Decimal(random.randint(150, 800)),
                        "price": n.purchase_price or Decimal("50"),
                    }
                    for n in chunk
                ]
                doc = await document_service.create_document(
                    session, doc_type=DocType.PRIHOD, subtype=DocSubtype.CREDIT,
                    doc_date=today - timedelta(days=14 - i // 10),
                    sklad_id=sklad.id, kontragent_id=supplier.id, items=items,
                )
                await document_service.post_document(session, doc)

        # --- Итог ---
        total = (
            await session.execute(select(func.count(cat.Nomenklatura.id)))
        ).scalar() or 0
        per_category = {
            name: len(items) for name, items in CATALOG.items()
        }
        print(f"Категорий: {len(CATALOG)}")
        print(f"Товаров создано за этот запуск: {len(created)}")
        print(f"Всего номенклатуры в базе: {total}")
        print("Распределение по категориям:")
        for name, count in per_category.items():
            print(f"  - {name}: {count}")


if __name__ == "__main__":
    asyncio.run(main())
